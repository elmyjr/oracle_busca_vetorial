-- =====================================================================
-- 01-create-table.sql: criação da tabela kb_docs
-- Projeto: busca vetorial de filmes (Grupo 3, MBA PUC Minas)
--
-- No compose, este arquivo é montado em /container-entrypoint-initdb.d
-- e roda UMA vez, na primeira subida do Oracle (volume vazio). Quem o
-- executa é o SQL*Plus, como SYS, conectado à raiz do banco (CDB), e
-- não ao FREEPDB1. Por isso as duas primeiras instruções:
--   1. entrar no FREEPDB1, onde está o usuário da aplicação;
--   2. fazer a tabela nascer no schema app_embedding, sem precisar da
--      senha dele (o SYS pode criar objetos em qualquer schema).
--
-- Para rodar à mão, conectado como app_embedding em FREEPDB1, pule as
-- duas instruções ALTER SESSION.
-- AVISO: rodar de novo apaga os filmes e obriga a refazer a carga.
-- =====================================================================

ALTER SESSION SET CONTAINER = FREEPDB1;
ALTER SESSION SET CURRENT_SCHEMA = app_embedding;

DROP TABLE IF EXISTS kb_docs;

-- VECTOR de 1024 dimensões: o tamanho é definido pelo modelo de
-- embedding (bge-m3); são 4096 bytes por vetor.
-- FLOAT32: o Ollama devolve números de 32 bits; FLOAT64 dobraria o
-- espaço sem ganhar precisão.
CREATE TABLE kb_docs (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo     VARCHAR2(200) NOT NULL,
    texto      CLOB NOT NULL,
    embedding  VECTOR(1024, FLOAT32) NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
